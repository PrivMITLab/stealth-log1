// Convert frontend payload + server geo into a DB row
function toRow(client, geo, geo2, vh, ip, linkId = null) {
  const b = v => (v === true ? 1 : v === false ? 0 : (v == null ? null : v));
  return {
    ip,
    country: geo.country || geo2.country || vh.country || null,
    countryCode: geo.countryCode || null,
    region: geo.regionName || geo2.region || vh.region || null,
    city: geo.city || geo2.city || vh.city || null,
    zip: geo.zip || geo2.postal || null,
    lat: parseFloat(geo.lat || vh.lat) || null,
    lon: parseFloat(geo.lon || vh.lon) || null,
    timezone: geo.timezone || vh.tz || null,
    isp: geo.isp || null,
    org: geo.org || geo2.org || null,
    asInfo: geo.as || null,
    proxy: geo.proxy ? 1 : 0,
    hosting: geo.hosting ? 1 : 0,
    mobile: geo.mobile ? 1 : 0,
    deviceType: client.deviceType || null,
    parsedOS: client.parsedOS || null,
    parsedBrowser: client.parsedBrowser || null,
    platform: client.platform || null,
    vendor: client.vendor || null,
    hardwareConcurrency: client.hardwareConcurrency != null ? String(client.hardwareConcurrency) : null,
    deviceMemory: client.deviceMemory || null,
    maxTouchPoints: client.maxTouchPoints != null ? Number(client.maxTouchPoints) : null,
    screenWidth: client.screenWidth || null,
    screenHeight: client.screenHeight || null,
    screenAvailWidth: client.screenAvailWidth || null,
    screenAvailHeight: client.screenAvailHeight || null,
    innerWidth: client.innerWidth || null,
    innerHeight: client.innerHeight || null,
    pixelRatio: client.pixelRatio || null,
    colorDepth: client.colorDepth || null,
    orientation: client.orientation || null,
    darkMode: client.darkMode || null,
    reducedMotion: client.reducedMotion || null,
    connectionType: client.connectionType || null,
    downlink: client.downlink || null,
    rtt: client.rtt || null,
    saveData: client.saveData != null ? String(client.saveData) : null,
    onLine: b(client.onLine),
    batteryLevel: client.batteryLevel || null,
    batteryCharging: client.batteryCharging || null,
    chargingTime: client.chargingTime || null,
    dischargingTime: client.dischargingTime || null,
    gpuVendor: client.gpuVendor || null,
    gpuRenderer: client.gpuRenderer || null,
    maxTextureSize: client.maxTextureSize || null,
    glVersion: client.glVersion || null,
    canvasFingerprint: client.canvasFingerprint || null,
    audioSampleRate: client.audioSampleRate || null,
    audioChannels: client.audioChannels || null,
    detectedFonts: client.detectedFonts || null,
    fontCount: client.fontCount || null,
    adBlocker: client.adBlocker || null,
    visitCount: client.visitCount || null,
    firstVisit: client.firstVisit || null,
    historyLength: client.historyLength || null,
    language: client.language || null,
    languages: client.languages || null,
    timezoneOffset: client.timezoneOffset != null ? Number(client.timezoneOffset) : null,
    localTime: client.localTime || null,
    referrer: client.referrer || null,
    currentURL: client.currentURL || null,
    cameras: client.cameras != null ? Number(client.cameras) : null,
    microphones: client.microphones != null ? Number(client.microphones) : null,
    speakers: client.speakers != null ? Number(client.speakers) : null,
    cookiesEnabled: b(client.cookiesEnabled),
    doNotTrack: client.doNotTrack || null,
    webGL: b(client.webGL),
    webRTC: b(client.webRTC),
    localStorage: b(client.localStorage),
    indexedDB: b(client.indexedDB),
    serviceWorker: b(client.serviceWorker),
    webAssembly: b(client.webAssembly),
    vibration: b(client.vibration),
    clipboard: b(client.clipboard),
    speechSynth: b(client.speechSynth),
    notification: client.notification || null,
    pdfViewerEnabled: b(client.pdfViewerEnabled),
    gamepad: b(client.gamepad),
    requestId: client.requestId || null,
    linkId: linkId || null,
    rawJson: JSON.stringify({ client, geo, geo2, vh }),
  };
}

module.exports = { toRow };
